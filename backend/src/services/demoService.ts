/**
 * SIMULATION ONLY. Every record created here is flagged `isDemo = true` and
 * shown with a DEMO label in the UI. All endpoints are disabled unless
 * DEMO_MODE_ENABLED=true and require an administrator.
 */

const FALLBACK_CENTER = { latitude: 11.0168, longitude: 76.9558 }; // Coimbatore

async function regionCenter(region: string) {
  const agg = await prisma.shelter.aggregate({
    where: { isActive: true, region: { equals: region, mode: 'insensitive' } },
    _avg: { latitude: true, longitude: true },
  });
  if (agg._avg.latitude === null || agg._avg.longitude === null) return FALLBACK_CENTER;
  return { latitude: agg._avg.latitude, longitude: agg._avg.longitude };
}

export async function simulateFloodAlert(region: string, actorId: string, ip?: string) {
  return createAlert(
    {
      title: `[DEMO] Flood warning — ${region}`,
      disasterTypeCode: 'FLOOD',
      severity: 'CRITICAL',
      region,
      message: `SIMULATION: Heavy rainfall has caused rising water levels in low-lying parts of ${region}.`,
      instruction:
        'SIMULATION: Move to higher ground. Avoid walking or driving through flood water. Keep your phone charged.',
      expiresAt: new Date(Date.now() + 6 * 3600_000).toISOString(),
    },
    actorId,
    { isDemo: true, ip },
  );
}

const pick = <T>(arr: readonly T[]): T => arr[randomInt(arr.length)]!;

const DEMO_PLACES = [
  'Near the bus stand, ground floor flooded',
  'Riverside colony, second street',
  'Behind the government school',
  'Market road, near the temple',
  'Railway underpass, water rising',
  'Lake view apartments, block B',
];

export async function simulateRescueRequests(region: string, count: number, actorId: string, ip?: string) {
  const center = await regionCenter(region);
  const created = [];
  for (let i = 0; i < count; i++) {
    const reqs = SPECIAL_REQUIREMENTS.filter(() => randomInt(4) === 0);
    const input: IncidentCreate = {
      clientId: randomUUID(),
      type: randomInt(3) === 0 ? pick(INCIDENT_TYPES) : pick(['FLOOD', 'TRAPPED', 'EVACUATION'] as const),
      severity: pick(SEVERITIES),
      peopleCount: pick(PEOPLE_COUNTS),
      specialRequirements: reqs,
      location: {
        // Scatter within roughly ±5 km of the region centre.
        latitude: center.latitude + (randomInt(-450, 450) / 10_000),
        longitude: center.longitude + (randomInt(-450, 450) / 10_000),
        accuracyMeters: randomInt(5, 60),
        text: `[DEMO] ${pick(DEMO_PLACES)}`,
        source: 'GPS',
      },
      description: 'SIMULATED REQUEST — generated by demo mode, not a real emergency.',
      clientCreatedAt: new Date(Date.now() - randomInt(0, 45) * 60_000).toISOString(),
    };
    const { incident } = await createIncident(input, { source: 'DIRECT', isDemo: true });
    created.push(incident.id);
  }
  await audit({ actorId, action: 'DEMO_RESCUE_REQUESTS', entityType: 'Incident', metadata: { region, count }, ipAddress: ip });
  return { created: created.length };
}

/** Randomly fills/empties shelters in a region to demonstrate capacity changes. */
export async function simulateShelterCapacity(region: string, actorId: string, ip?: string) {
  const shelters = await prisma.shelter.findMany({
    where: { isActive: true, region: { equals: region, mode: 'insensitive' }, status: { not: 'CLOSED' } },
  });
  if (shelters.length === 0) throw new AppError(404, 'NOT_FOUND', `No shelters found in ${region}.`);
  for (const s of shelters) {
    const occupancy = Math.min(s.capacity, Math.round(s.capacity * (randomInt(20, 101) / 100)));
    await prisma.shelter.update({
      where: { id: s.id },
      data: { occupancy, status: occupancy >= s.capacity ? 'FULL' : 'OPEN' },
    });
  }
  await audit({ actorId, action: 'DEMO_SHELTER_CAPACITY', entityType: 'Shelter', metadata: { region, count: shelters.length }, ipAddress: ip });
  return { updated: shelters.length };
}

/** Removes all simulated incidents and alerts. Real data is never touched. */
export async function resetDemoData(actorId: string, ip?: string) {
  const [incidents, alerts] = await prisma.$transaction([
    prisma.incident.deleteMany({ where: { isDemo: true } }),
    prisma.alert.deleteMany({ where: { isDemo: true } }),
  ]);
  await audit({
    actorId,
    action: 'DEMO_RESET',
    entityType: 'System',
    metadata: { incidents: incidents.count, alerts: alerts.count },
    ipAddress: ip,
  });
  return { incidentsRemoved: incidents.count, alertsRemoved: alerts.count };
}
